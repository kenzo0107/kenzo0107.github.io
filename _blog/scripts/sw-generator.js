/**
 * Generates sw.js with the current build timestamp embedded as the cache version.
 * Cache-first for static assets, stale-while-revalidate for HTML.
 */
hexo.extend.generator.register('service-worker', function() {
    const buildDate = new Date().toISOString().slice(0, 10).replace(/-/g, '');
    const cacheVersion = `v1-${buildDate}`;

    const swContent = `/* Auto-generated by sw-generator.js */
const CACHE = 'blog-${cacheVersion}';
const STATIC = [
  '/css/default.css',
  '/webfonts/fa-solid-900.woff2',
  '/webfonts/fa-brands-400.woff2',
  '/fonts/jetbrains-mono-400.woff2',
  '/fonts/jetbrains-mono-600.woff2',
  '/js/main.js',
  '/js/insight.js',
  '/js/animation.js',
  '/js/column.js',
  '/js/back_to_top.js',
  '/js/toc.js',
  '/js/pace.min.js',
  '/js/lightgallery.min.js',
  '/css/lightgallery-bundle.min.css',
  '/manifest.json',
  '/img/logo.svg',
  '/img/favicon.svg',
  '/img/avatar.webp',
];

self.addEventListener('install', e => {
  e.waitUntil(
    caches.open(CACHE).then(c =>
      Promise.allSettled(STATIC.map(url => c.add(url)))
    )
  );
  self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil(
    Promise.all([
      caches.keys().then(keys =>
        Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))
      ),
      self.registration.navigationPreload && self.registration.navigationPreload.enable(),
    ])
  );
  self.clients.claim();
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  // /toda-tocochan-bus/ は独自ファイルを頻繁に更新するためキャッシュしない
  if (url.pathname.startsWith('/toda-tocochan-bus/')) return;
  if (/\\.(css|js|json|svg|png|jpg|jpeg|gif|webp|ico|woff2?)$/.test(url.pathname)) {
    e.respondWith(
      caches.match(e.request).then(cached => {
        const net = fetch(e.request).then(res => {
          if (res.ok) caches.open(CACHE).then(c => c.put(e.request, res.clone()));
          return res;
        }).catch(() => cached || Response.error());
        return cached || net;
      }).catch(() => Response.error())
    );
    return;
  }
  // Stale-while-revalidate for HTML navigation requests: serve cached version
  // immediately, then update cache in background. Safe because the daily cache
  // name change (embedded at build time) forces full re-fetch after each new deployment.
  // Use Navigation Preload response (if available) to avoid waiting for SW startup.
  if (e.request.mode === 'navigate') {
    e.respondWith(
      caches.open(CACHE).then(cache =>
        cache.match(e.request).then(cached => {
          const net = (e.preloadResponse || Promise.resolve(null)).then(preloaded =>
            (preloaded || fetch(e.request)).then(res => {
              if (res && res.ok) cache.put(e.request, res.clone());
              return res;
            })
          ).catch(() => cached || fetch(e.request).catch(() => Response.error()));
          return cached || net;
        })
      ).catch(() => fetch(e.request).catch(() => Response.error()))
    );
    return;
  }
  e.respondWith(
    fetch(e.request).catch(() =>
      caches.match(e.request).then(r => r || Response.error())
    )
  );
});
`;

    return { path: 'sw.js', data: swContent };
});
